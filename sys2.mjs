import { chromium } from "playwright";
const b = await chromium.launch({ channel: "chrome" });
const p = await (await b.newContext({ viewport: { width: 1200, height: 800 } })).newPage();
const errs = [];
p.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 200)); });
p.on("pageerror", (e) => errs.push("pageerror " + e.message.slice(0, 200)));
const r = await p.goto("https://road-to-bal.vercel.app/xyz", { waitUntil: "domcontentloaded" });
console.log("status", r.status());
await p.waitForTimeout(12000);
console.log(JSON.stringify(await p.evaluate(() => ({ cls: document.querySelector("main")?.className, text: document.querySelector("main")?.innerText.slice(0, 80), html404: document.documentElement.innerHTML.includes("NEXT_HTTP_ERROR_FALLBACK;404"), robots: document.querySelector('meta[name=robots]')?.content }))), JSON.stringify(errs));
await b.close();
