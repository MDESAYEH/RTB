type PlayerLike = { id: string; name: string };

/** "ALSHWETER" -> "Alshweter"; single letters and mixed-case words stay as FIBA wrote them. */
function tidyEnglish(name: string): string {
  return name
    .split(/\s+/)
    .map((word) =>
      word.length > 1 && word === word.toUpperCase() && /[A-Z]/.test(word)
        ? word.charAt(0) + word.slice(1).toLowerCase()
        : word,
    )
    .join(" ");
}

export function playerName(player: PlayerLike, lang: "ar" | "en"): string {
  if (lang === "ar") {
    const id = Number(player.id.match(/^fiba-player-(\d+)$/)?.[1]);
    return ARABIC_NAMES[id] ?? tidyEnglish(player.name);
  }
  return tidyEnglish(player.name);
}
